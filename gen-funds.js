    id: id,
    symbol: symbol,
    name: name,
    exchange: "IDX",
    sector: sector,
    industry: industry,
    image: `https://www.google.com/s2/favicons?domain=${domain}&sz=128`,
    domain: domain,
    basePrice: basePrice,
    volatility: 0.01 + Math.random() * 0.02,
    change_1d: (Math.random() * 4 - 2).toFixed(2),
    change_1w: (Math.random() * 8 - 4).toFixed(2),
    change_1m: (Math.random() * 15 - 7.5).toFixed(2),
    change_1y: (Math.random() * 40 - 20).toFixed(2),
